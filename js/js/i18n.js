function t(clave, vars) {
  let s = TEXTOS[LANG][clave] ?? TEXTOS.es[clave] ?? clave;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
  return s;
}

